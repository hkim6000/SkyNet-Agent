CREATE TABLE [dbo].[ITEM](
    [ITEM_ID]    NVARCHAR(50)   NOT NULL,
    [ITEM_NAME]  NVARCHAR(100)  NOT NULL,
    [CATEGORY]   NVARCHAR(50)   NOT NULL CONSTRAINT [DF_ITEM_CATEGORY] DEFAULT (N''),
    [PRICE]      DECIMAL(18, 2) NOT NULL CONSTRAINT [DF_ITEM_PRICE] DEFAULT (0),
    [STOCK]      INT            NOT NULL CONSTRAINT [DF_ITEM_STOCK] DEFAULT (0),
    [ACTIVE]     BIT            NOT NULL CONSTRAINT [DF_ITEM_ACTIVE] DEFAULT (1),
    [SYSDTE]     DATETIME       NOT NULL CONSTRAINT [DF_ITEM_SYSDTE] DEFAULT (GETDATE()),
    CONSTRAINT [PK_ITEM] PRIMARY KEY CLUSTERED ([ITEM_ID] ASC)
)
GO

CREATE UNIQUE INDEX [UX_ITEM_ITEM_NAME] ON [dbo].[ITEM] ([ITEM_NAME])
